  assert.equal(await app.locator('[data-summary-pulls]').innerText(),'3 次');
  await snap('deposit-desktop');await act('start-put').click();
  await app.getByRole('heading',{name:'文件已寄存',exact:true}).waitFor();
  await snap('deposit-success');await act('copy').click();assert((await app.getByRole('status').innerText()).includes('演示'));
  await act('home').last().click();assert.equal(await app.locator('.lk-file').count(),4);
  results.push('select first, explicit deposit, rule summary, async simulated progress, sharing handoff');
  await act('take').click();await act('lookup').click();assert((await app.getByRole('alert').innerText()).includes('6 位'));
  await app.locator('[data-input=code]').fill('999999');await act('lookup').click();assert((await app.getByRole('alert').innerText()).includes('不匹配'));
  await app.locator('[data-input=code]').fill('１２３ ４５６');await act('lookup').click();
  assert(await act('receive').isVisible());await snap('pickup-desktop');
  await app.locator('[data-input=target][value=vault]').check();await act('receive').click();
  assert((await app.innerText()).includes('文件已保存'));
  await act('home').last().click();await act('take').click();await app.locator('[data-receive=share]').click();
  await app.locator('[data-input=code]').fill('123456');await act('lookup').click();assert((await app.getByRole('alert').innerText()).includes('完整分享链接'));
