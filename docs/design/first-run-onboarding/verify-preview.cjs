const { chromium } = require('C:/Users/hgc18/AppData/Local/GitKeymasterDev/design-tools/node_modules/playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');

(async () => {
  const html = fs.readFileSync(path.join(__dirname, 'preview.html'));
  const server = http.createServer((req, res) => {
    if (req.url === '/favicon.ico') { res.writeHead(204); res.end(); return; }
    res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end(html);
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  console.log(`Preview server: ${url}`);
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const context = await browser.newContext({ viewport: { width: 1100, height: 1100 }, deviceScaleFactor: 1.5, colorScheme: 'light' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  try {
    await page.goto(url);
    const frame = page.frameLocator('iframe');
    const wizard = frame.locator('[data-design="wizard"]');
    await wizard.locator('[data-panel="0"]').waitFor();
    await wizard.locator('[data-theme="dark"]').hover();
    assert.equal(await wizard.locator('[data-theme="light"]').getAttribute('aria-pressed'), 'true');
    await wizard.locator('[data-preview]').click();
    await wizard.locator('[data-preview-status]').filter({ hasText: '预览结束' }).waitFor();
    for (const theme of ['dark', 'navy', 'light']) {
      await wizard.locator(`[data-theme="${theme}"]`).click();
      assert.equal(await wizard.getAttribute('data-selected-theme'), theme);
    }
    await wizard.locator('[data-style="经典"]').click();
    await wizard.locator('[data-style="极简"]').click();
    await wizard.locator('[data-preview-status]').evaluate(el => el.textContent = '');
    await wizard.screenshot({ path: path.join(__dirname, '01-experience-desktop.png') });
    await wizard.locator('[data-next]').click();
    const protect = wizard.locator('[data-key="protect"]');
    assert(await protect.isChecked());
    assert.match(await wizard.locator('[data-capture-note]').innerText(), /当前未开启.*保存后开启/);
    await protect.uncheck();
    assert.match(await wizard.locator('[data-capture-note]').innerText(), /保持关闭/);
    await protect.check();
    await wizard.locator('[data-key="idle"]').selectOption('0');
    assert(await wizard.locator('[data-idle-warning]').isVisible());
    await wizard.locator('[data-key="idle"]').selectOption('5');
    await wizard.locator('[data-panel="1"] summary').click();
    await wizard.locator('[data-key="reveal"]').selectOption('0');
    await wizard.locator('[data-key="mask"]').uncheck();
    await wizard.locator('[data-key="watch"]').check();
    await wizard.locator('[data-next]').click();
    assert.match(await wizard.locator('[data-summary]').innerText(), /每次验证/);
    assert.match(await wizard.locator('[data-summary]').innerText(), /关闭 \/ 开启/);
    await wizard.locator('[data-back]').click();
    assert.equal(await wizard.locator('[data-key="reveal"]').inputValue(), '0');
    await wizard.locator('[data-key="reveal"]').selectOption('1');
    await wizard.locator('[data-key="mask"]').check();
    await wizard.locator('[data-key="watch"]').uncheck();
    await wizard.locator('[data-panel="1"] summary').click();
    await wizard.screenshot({ path: path.join(__dirname, '02-security-desktop.png') });
    await wizard.locator('[data-next]').click();
    await wizard.screenshot({ path: path.join(__dirname, '03-confirm-desktop.png') });
    await wizard.locator('[data-next]').click();
    assert.match(await wizard.locator('[data-finish-message]').innerText(), /截图防护已选择开启/);
    await wizard.locator('[data-workspace="create"]').click();
    assert.match(await wizard.locator('[data-workspace-status]').innerText(), /选择工作空间/);
    await wizard.locator('[data-next]').click();
    await wizard.locator('[data-skip]').click();
    assert.match(await wizard.locator('[data-finish-message]').innerText(), /截图防护仍关闭/);
    await wizard.locator('[data-next]').click();
    await wizard.locator('[data-step="1"]').click();
    await protect.uncheck();
    await wizard.locator('[data-next]').click();
    assert.match(await wizard.locator('[data-summary]').innerText(), /保持关闭/);
    await wizard.locator('[data-next]').click();
    assert.match(await wizard.locator('[data-finish-message]').innerText(), /保持关闭/);
    await wizard.locator('[data-next]').click();
    await wizard.locator('[data-step="1"]').click();
    await protect.check();

    // Exercise the same interactions after responsive resizing, including touch.
    for (const width of [736, 390, 320]) {
      await page.setViewportSize({ width: width + 32, height: 1500 });
      const overflow = await wizard.evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth }));
      assert(overflow.scroll <= overflow.width + 1, `Horizontal overflow at ${width}: ${JSON.stringify(overflow)}`);
      await protect.uncheck(); await protect.check();
      await wizard.locator('[data-next]').click();
      assert.match(await wizard.locator('[data-summary]').innerText(), /保存后开启/);
      await wizard.locator('[data-back]').click();
      if (width === 390) await wizard.screenshot({ path: path.join(__dirname, '04-security-mobile.png') });
      if (width === 320) await wizard.screenshot({ path: path.join(__dirname, '06-mobile-320.png') });
    }
    await page.setViewportSize({ width: 1100, height: 1100 });
    await wizard.locator('[data-step="0"]').click();
    await wizard.locator('[data-theme="dark"]').click();
    await wizard.locator('[data-step="1"]').click();
    assert.equal(await wizard.locator('[data-panel="1"] h1').evaluate(el => getComputedStyle(el).color), 'rgb(241, 245, 249)');
    await wizard.screenshot({ path: path.join(__dirname, '05-security-dark.png') });
    await wizard.locator('[data-step="0"]').click();
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await wizard.locator('[data-preview]').click();
    assert.match(await wizard.locator('[data-preview-status]').innerText(), /减少动态效果/);
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await wizard.locator('[data-theme="light"]').click();
    await wizard.locator('[data-preview-status]').evaluate(el => el.textContent = '');
    // Verify host-supplied carousel navigation rather than replacing its behavior.
    const carouselControls = await frame.locator('.viz-carousel button').allTextContents();
    fs.writeFileSync(path.join(__dirname, 'carousel-controls.json'), JSON.stringify(carouselControls, null, 2));
    const nextVariant = frame.getByRole('button', { name: '下一个方案', exact: true });
    await nextVariant.click();
    const quick = frame.locator('[data-design="quick"]');
    await quick.waitFor({ state: 'visible' });
    await quick.locator('[data-quick-protect]').uncheck();
    assert.match(await quick.locator('[data-quick-capture]').innerText(), /保持关闭/);
    await quick.locator('[data-quick-protect]').check();
    await quick.locator('[data-quick-save]').click();
    assert.match(await quick.locator('[data-quick-result]').innerText(), /偏好已确认/);
    await quick.locator('[data-quick-skip]').click();
    assert.match(await quick.locator('[data-quick-result]').innerText(), /仍关闭/);
    await quick.locator('[data-quick-result]').evaluate(el => el.textContent = '');
    await quick.screenshot({ path: path.join(__dirname, '07-quick-alternative.png') });
    await frame.getByRole('button', { name: '上一个方案', exact: true }).click();
    await wizard.waitFor({ state: 'visible' });
    assert.equal(await wizard.locator('[data-key="reveal"]').inputValue(), '1');
    await wizard.locator('[data-step="1"]').focus();
    await page.keyboard.press('Enter');
    assert(await wizard.locator('[data-panel="1"]').isVisible());
    const touchContext = await browser.newContext({ viewport: { width: 422, height: 1500 }, deviceScaleFactor: 1.5, isMobile: true, hasTouch: true, colorScheme: 'light' });
    const touchPage = await touchContext.newPage();
    touchPage.on('pageerror', error => errors.push(error.message));
    await touchPage.goto(url);
    const touchWizard = touchPage.frameLocator('iframe').locator('[data-design="wizard"]');
    await touchWizard.locator('[data-next]').tap();
    await touchWizard.locator('[data-key="protect"]').tap();
    assert.match(await touchWizard.locator('[data-capture-note]').innerText(), /保持关闭/);
    await touchWizard.locator('[data-key="protect"]').tap();
    await touchWizard.screenshot({ path: path.join(__dirname, '04-security-mobile.png') });
    await touchPage.setViewportSize({ width: 352, height: 1500 });
    const touchOverflow = await touchWizard.evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth }));
    assert(touchOverflow.scroll <= touchOverflow.width + 1, 'Touch layout overflow');
    await touchWizard.screenshot({ path: path.join(__dirname, '06-mobile-320.png') });
    await touchContext.close();
    assert.deepEqual(errors, [], 'Browser errors');
    fs.writeFileSync(path.join(__dirname, 'verification.json'), JSON.stringify({ passed: true, viewportWidths: [1068, 736, 390, 320], themes: ['light', 'dark', 'navy'], checked: ['wizard navigation', 'draft capture state', 'preserved back navigation', 'save on/off', 'skip retains initial off', 'disclosures', 'theme selection', 'dark text contrast', 'motion preview', 'reduced motion', 'carousel', 'narrow layout', 'hover', 'keyboard activation', 'touch interaction'], errors }, null, 2));
    console.log('Design interactions passed; screenshots saved.');
  } finally { await context.close(); await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(err => { console.error(err); process.exitCode = 1; });
